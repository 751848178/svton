import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { JobStore } from './jobs.js';
import { jobControlRoutes, cursorLog } from './routes-job-control.js';
import type { RouteCtx, RouteDeps } from './route-types.js';
test('job control rejects cross-role cancellation and validates cursors', async (t) => {
  const dir = await mkdtemp(path.join(tmpdir(), 'ship-job-routes-'));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const jobs = new JobStore(dir);
  let release!: () => void;
  const gate = new Promise<void>((resolve) => { release = resolve; });
  const job = await jobs.create('group-deploy', async (ctx) => { await gate; ctx.checkpoint(); }, true);
  const deps = { jobs } as RouteDeps;
  const ctx = { params: [job.id], query: new URLSearchParams(), auth: { role: 'builder' }, json: {} } as RouteCtx;
  const cancel = jobControlRoutes(deps).find((route) => route.method === 'POST')!;
  await assert.rejects(cancel.handler(ctx), /requires runtime credentials/);
  ctx.auth = { role: 'runtime' };
  ctx.query.set('offset', '-1');
  await assert.rejects(cursorLog(deps, ctx), /invalid cursor/);
  ctx.query.set('offset', '0'); ctx.query.set('limit', '131073');
  await assert.rejects(cursorLog(deps, ctx), /invalid cursor/);
  const accepted = await cancel.handler(ctx);
  assert.equal(accepted.status, 202);
  release();
  while (jobs.activeCount()) await new Promise((resolve) => setTimeout(resolve, 2));
  assert.equal(jobs.get(job.id)?.status, 'cancelled');
  assert.equal((await cancel.handler(ctx)).status, 200, 'terminal cancellation is idempotent');
});
