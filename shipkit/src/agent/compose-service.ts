// Per-service compose rendering for v2 groups (MS-03): each service of a
// group gets its OWN compose project and file under services/<name>/, so an
// unselected service's project is never rewritten and never restarts. The
// project name `ship_<group>_<service>` is collision-free: underscore cannot
// appear in group or service names.

import path from 'node:path';
import type { ServiceSpec } from '../shared/spec-v2.js';
import { parseVolumeMount } from '../shared/spec-v2.js';
import { RUNTIME_ENV_FILE, writeComposeFile } from './compose.js';
import { parseRuntimeEnv } from '../shared/runtime-env.js';
export { selectedHostPort as serviceExplicitHostPort, selectedContainerPort as serviceFirstContainerPort } from './port-selection.js';

const q = (s: string) => JSON.stringify(s);

/** v2 per-service compose project — underscore separator cannot appear in names */
export function serviceProject(group: string, service: string): string {
  return `ship_${group}_${service}`;
}

export function serviceDir(appsRoot: string, group: string, service: string): string {
  return path.join(appsRoot, group, 'services', service);
}

export function renderServiceCompose(group: string, service: string, imageRef: string, spec: ServiceSpec, withEnvFile: boolean, envContent?: string): string {
  const lines: string[] = [
    '# generated by ship-agent — manual edits will be overwritten',
    'services:',
    `  ${service}:`,
    `    image: ${q(imageRef)}`,
    '    restart: unless-stopped',
  ];
  if (spec.ports?.length) {
    lines.push('    ports:');
    for (const p of spec.ports) lines.push(`      - ${q(p)}`);
  }
  const runtimeEnv = envContent === undefined ? undefined : parseRuntimeEnv(envContent);
  if (runtimeEnv) {
    lines.push('    environment:');
    for (const [key, value] of Object.entries(runtimeEnv)) lines.push(`      ${key}: ${q(value.replace(/\$/g, '$$$$'))}`);
    if (!Object.keys(runtimeEnv).length) lines[lines.length - 1] = '    environment: {}';
  } else if (withEnvFile) lines.push('    env_file:', `      - ${q(RUNTIME_ENV_FILE)}`);
  const namedVolumes: string[] = [];
  if (spec.volumes?.length) {
    lines.push('    volumes:');
    for (const v of spec.volumes) {
      const m = parseVolumeMount(v, 'volumes');
      // named external volumes MUST also appear in the top-level section with
      // external:true + explicit name — otherwise compose treats the reference
      // as undefined (R04) or would auto-create a project volume
      if (m.kind === 'volume') namedVolumes.push(m.source);
      lines.push(`      - ${q(`${m.source}:${m.target}${m.readOnly ? ':ro' : ''}`)}`);
    }
  }
  if (spec.networks?.length) {
    lines.push('    networks:');
    for (const n of spec.networks) lines.push(`      - ${q(n)}`);
    lines.push('networks:');
    for (const n of spec.networks) lines.push(`  ${n}:`, `    name: ${q(n)}`, '    external: true');
  }
  if (namedVolumes.length > 0) {
    lines.push('volumes:');
    for (const v of [...new Set(namedVolumes)]) lines.push(`  ${v}:`, `    name: ${q(v)}`, '    external: true');
  }
  return `${lines.join('\n')}\n`;
}

export function writeServiceCompose(dir: string, content: string): Promise<void> {
  return writeComposeFile(dir, content);
}
