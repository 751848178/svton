// Compose rendering + port semantics (F15 control-plane isolation, F26 explicit vs dynamic host ports).

import path from 'node:path';
import type { ShipSpec } from '../shared/types.js';
import { writeFileAtomic } from './atomic.js';
import { renderRuntimePolicy } from './compose-runtime-policy.js';
export { selectedHostPort as explicitHostPort, selectedContainerPort as firstContainerPort } from './port-selection.js';

const q = (s: string) => JSON.stringify(s);

/** empty file pinned via --env-file: app secrets must NOT control compose interpolation/project name (F15) */
export const COMPOSE_ENV_FILE = 'compose.env';
/** service env file name — deliberately not `.env` so compose never treats it as the control plane */
export const RUNTIME_ENV_FILE = 'runtime.env';

export function renderComposeFile(app: string, imageRef: string, spec: ShipSpec, withEnvFile: boolean): string {
  const lines: string[] = [
    '# generated by ship-agent — manual edits will be overwritten',
    'services:',
    `  ${app}:`,
    `    image: ${q(imageRef)}`,
    ...renderRuntimePolicy(spec.runtime),
  ];
  if (spec.ports?.length) {
    lines.push('    ports:');
    for (const p of spec.ports) lines.push(`      - ${q(p)}`);
  }
  if (withEnvFile) {
    lines.push('    env_file:', `      - ${q(RUNTIME_ENV_FILE)}`);
  }
  return `${lines.join('\n')}\n`;
}

export async function writeComposeFile(appDir: string, content: string): Promise<void> {
  await writeFileAtomic(path.join(appDir, 'compose.yaml'), content, 0o600);
}
